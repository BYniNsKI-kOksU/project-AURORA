def _range_from_header(header, size):
    if not header:
        return None
    if not header.startswith("bytes=") or "," in header:
        raise ValueError("Unsupported byte range")
    try:
        start_text, end_text = header[6:].split("-", 1)
        if start_text:
            start = int(start_text)
            end = int(end_text) if end_text else size - 1
        else:
            length = int(end_text)
            if length <= 0:
                raise ValueError("Invalid suffix length")
            start = max(0, size - length)
            end = size - 1
        if start < 0 or end < start or start >= size:
            raise ValueError("Byte range outside resource")
        return start, min(end, size - 1)
    except (TypeError, ValueError) as error:
        raise ValueError("Invalid byte range") from error


def create_handler(payload_bytes, sky_map_path):
    html_bytes = APP_HTML.encode("utf-8")
    favicon_bytes = FAVICON.encode("utf-8")
    compressed_payload = gzip.compress(payload_bytes, compresslevel=6)
    compressed_html = gzip.compress(html_bytes, compresslevel=6)
    payload_etag = f'"{hashlib.sha256(payload_bytes).hexdigest()[:24]}"'
    html_etag = f'"{hashlib.sha256(html_bytes).hexdigest()[:24]}"'
    sky_stat = sky_map_path.stat()
    sky_etag = f'"{sky_stat.st_size:x}-{sky_stat.st_mtime_ns:x}"'

    class AuroraHandler(BaseHTTPRequestHandler):
        server_version = "AURORA/1.0"

        def log_message(self, format_string, *args):
            if getattr(self.server, "verbose", False):
                super().log_message(format_string, *args)

        def _security_headers(self):
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("X-Frame-Options", "DENY")
            self.send_header("Referrer-Policy", "no-referrer")
            self.send_header("Cross-Origin-Resource-Policy", "same-origin")
            self.send_header(
                "Content-Security-Policy",
                "default-src 'self'; script-src 'self' 'unsafe-inline'; "
                "style-src 'self' 'unsafe-inline'; img-src 'self' data:; "
                "connect-src 'self'; object-src 'none'; base-uri 'none'; "
                "frame-ancestors 'none'",
            )

        def _send_bytes(
            self,
            content,
            content_type,
            cache="no-store",
            *,
            etag=None,
            compressed=None,
        ):
            if etag and self.headers.get("If-None-Match") == etag:
                self.send_response(HTTPStatus.NOT_MODIFIED)
                self.send_header("ETag", etag)
                self.send_header("Cache-Control", cache)
                self._security_headers()
                self.end_headers()
                return
            use_gzip = (
                compressed is not None
                and "gzip" in self.headers.get("Accept-Encoding", "").lower()
            )
            body = compressed if use_gzip else content
            self.send_response(HTTPStatus.OK)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", cache)
            if etag:
                self.send_header("ETag", etag)
            if compressed is not None:
                self.send_header("Vary", "Accept-Encoding")
            if use_gzip:
                self.send_header("Content-Encoding", "gzip")
            self._security_headers()
            self.end_headers()
            if self.command != "HEAD":
                try:
                    self.wfile.write(body)
                except (BrokenPipeError, ConnectionResetError):
                    return

        def _send_sky_map(self):
            size = sky_map_path.stat().st_size
            try:
                byte_range = _range_from_header(self.headers.get("Range"), size)
            except ValueError:
                self.send_response(HTTPStatus.REQUESTED_RANGE_NOT_SATISFIABLE)
                self.send_header("Content-Range", f"bytes */{size}")
                self.send_header("Content-Length", "0")
                self._security_headers()
                self.end_headers()
                return
            if not byte_range and self.headers.get("If-None-Match") == sky_etag:
                self.send_response(HTTPStatus.NOT_MODIFIED)
                self.send_header("ETag", sky_etag)
                self.send_header("Cache-Control", "public, max-age=3600")
                self._security_headers()
                self.end_headers()
                return
            start, end = byte_range if byte_range else (0, size - 1)
            status = HTTPStatus.PARTIAL_CONTENT if byte_range else HTTPStatus.OK
            self.send_response(status)
            self.send_header("Content-Type", mimetypes.guess_type(sky_map_path.name)[0] or "image/png")
            self.send_header("Content-Length", str(end - start + 1))
            self.send_header("Accept-Ranges", "bytes")
            self.send_header("Cache-Control", "public, max-age=3600")
            self.send_header("ETag", sky_etag)
            if byte_range:
                self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
            self._security_headers()
            self.end_headers()
            if self.command == "HEAD":
                return
            with sky_map_path.open("rb") as file:
                file.seek(start)
                remaining = end - start + 1
                while remaining:
                    MEMORY.throttle()
                    chunk = file.read(min(1024 * 1024, remaining))
                    if not chunk:
                        break
                    try:
                        self.wfile.write(chunk)
                    except (BrokenPipeError, ConnectionResetError):
                        return
                    remaining -= len(chunk)

        def do_GET(self):
            path = unquote(urlsplit(self.path).path)
            if path == "/":
                self._send_bytes(
                    html_bytes,
                    "text/html; charset=utf-8",
                    "no-cache",
                    etag=html_etag,
                    compressed=compressed_html,
                )
            elif path == "/api/events":
                self._send_bytes(
                    payload_bytes,
                    "application/json; charset=utf-8",
                    "private, max-age=60",
                    etag=payload_etag,
                    compressed=compressed_payload,
                )
            elif path == "/sky-map":
                self._send_sky_map()
            elif path == "/favicon.svg":
                self._send_bytes(favicon_bytes, "image/svg+xml", "public, max-age=86400")
            else:
                self.send_error(HTTPStatus.NOT_FOUND, "Not found")

        do_HEAD = do_GET

    return AuroraHandler


def parse_args():
    parser = argparse.ArgumentParser(
        description="Interactive AURORA map of Gaia DR3 microlensing events.",
    )
    parser.add_argument(
        "--catalog",
        type=Path,
        default=DEFAULT_CATALOG,
        help="Input FITS catalogue",
    )
    parser.add_argument(
        "--map",
        dest="sky_map",
        type=Path,
        help="Hammer PNG from aurora_sky_render.py",
    )
    parser.add_argument(
        "--host",
        default=DEFAULT_SERVER_HOST,
        help="Local server address",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=DEFAULT_SERVER_PORT,
        help="Port; 0 chooses a free port",
    )
    parser.add_argument(
        "--no-browser",
        action="store_true",
        help="Do not open the browser automatically",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Print HTTP request logs",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    MEMORY.throttle()
    catalog_path = args.catalog.expanduser().resolve()
    if not catalog_path.is_file():
        raise FileNotFoundError(f"Microlensing catalogue does not exist: {catalog_path}")
    sky_map_path = find_sky_map(args.sky_map)

    console.print("\n[AURORA] Interactive microlensing atlas")
    console.print("─" * 45)
    MEMORY.throttle()
    payload = load_event_payload(catalog_path)
    payload_bytes = json.dumps(
        payload,
        ensure_ascii=False,
        separators=(",", ":"),
    ).encode("utf-8")
    console.print(f"  ✓ Sky background: {sky_map_path}")

    server = ThreadingHTTPServer(
        (args.host, args.port),
        create_handler(payload_bytes, sky_map_path),
    )
    server.verbose = args.verbose
    browser_host = (
        "127.0.0.1"
        if args.host == "0.0.0.0"
        else "[::1]"
        if args.host == "::"
        else f"[{args.host}]"
        if ":" in args.host and not args.host.startswith("[")
        else args.host
    )
    url = f"http://{browser_host}:{server.server_address[1]}/"
    console.print(f"  ✓ Atlas ready: {url}")
    console.print("  → Press Ctrl+C to stop")

    if not args.no_browser:
        timer = threading.Timer(0.35, webbrowser.open, args=(url,))
        timer.daemon = True
        timer.start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        console.print("\n  ✓ Atlas stopped")
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
