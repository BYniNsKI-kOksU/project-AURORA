def _finite(value, default=None):
    """Return a JSON-safe scalar or a default for masked/non-finite values."""
    if np.ma.is_masked(value):
        return default
    try:
        number = float(value)
    except (TypeError, ValueError):
        return default
    return number if math.isfinite(number) else default


def _first_finite(row, names):
    for name in names:
        if name in row.colnames:
            value = _finite(row[name])
            if value is not None:
                return value, name
    return None, None


def _temperature_from_row(row):
    temperature = _finite(row["teff_gspphot"]) if "teff_gspphot" in row.colnames else None
    if temperature is not None:
        return temperature, "Gaia teff_gspphot"

    colour = _finite(row["bp_rp"]) if "bp_rp" in row.colnames else None
    if colour is not None:
        colour = min(4.0, max(-0.5, colour))
        temperature = 4600.0 * (
            1.0 / (0.92 * colour + 1.7)
            + 1.0 / (0.92 * colour + 0.62)
        )
        return temperature, "oszacowanie z BP−RP"
    return None, None


def _source_colour_from_row(row):
    teff = _finite(row["teff_gspphot"]) if "teff_gspphot" in row.colnames else None
    bp_rp = _finite(row["bp_rp"]) if "bp_rp" in row.colnames else None
    rgb = star_colors_from_columns(
        np.array([np.nan if teff is None else teff], dtype=np.float32),
        np.array([np.nan if bp_rp is None else bp_rp], dtype=np.float32),
    )[0]
    rgb = np.clip(np.asarray(rgb, dtype=np.float32), 0.0, 1.0)
    rgb255 = tuple(int(round(float(channel) * 255.0)) for channel in rgb)
    return {
        "rgb": [round(float(channel), 4) for channel in rgb],
        "css": f"rgb({rgb255[0]}, {rgb255[1]}, {rgb255[2]})",
        "hex": f"#{rgb255[0]:02x}{rgb255[1]:02x}{rgb255[2]:02x}",
    }


def _spectral_description(temperature):
    if temperature is None:
        return "Gwiazda źródłowa — typ widmowy nieustalony"
    if temperature >= 30_000:
        spectral = "O"
    elif temperature >= 10_000:
        spectral = "B"
    elif temperature >= 7_500:
        spectral = "A"
    elif temperature >= 6_000:
        spectral = "F"
    elif temperature >= 5_200:
        spectral = "G"
    elif temperature >= 3_700:
        spectral = "K"
    else:
        spectral = "M"
    return f"Gwiazda źródłowa — przybliżony typ {spectral}"


def _hammer_position(longitude_deg, latitude_deg):
    """Return normalized pixels matching aurora_sky_render.py."""
    longitude = longitude_deg
    if longitude > 180.0:
        longitude -= 360.0
    longitude = -math.radians(longitude)
    latitude = math.radians(latitude_deg)

    cos_b = math.cos(latitude)
    half_l = longitude * 0.5
    z = math.sqrt(1.0 + cos_b * math.cos(half_l))
    x_hammer = 2.0 * math.sqrt(2.0) * cos_b * math.sin(half_l) / z
    y_hammer = math.sqrt(2.0) * math.sin(latitude) / z
    x = (x_hammer / (2.0 * math.sqrt(2.0)) + 1.0) * 0.5
    y = (1.0 - y_hammer / math.sqrt(2.0)) * 0.5
    return x, y


def _maximum_amplification(u0):
    u2 = max(u0 * u0, np.finfo(np.float64).tiny)
    return (u2 + 2.0) / math.sqrt(u2 * (u2 + 4.0))


def _gaia_date(tmax):
    """Convert Gaia DR3 BJD(TCB)-2455197.5 to an approximate UTC date."""
    time_tcb = Time(tmax + GAIA_TIME_ZERO_JD, format="jd", scale="tcb")
    utc = time_tcb.utc.to_datetime(timezone=timezone.utc)
    return {
        "iso": utc.isoformat().replace("+00:00", "Z"),
        "date": utc.strftime("%Y-%m-%d"),
        "label": utc.strftime("%d.%m.%Y"),
        "bjd": tmax + GAIA_TIME_ZERO_JD,
    }


def _estimate_lens_mass(
    timescale_days,
    source_distance_pc,
    *,
    lens_distance_fraction=ASSUMED_LENS_DISTANCE_FRACTION,
    transverse_speed_kms=ASSUMED_TRANSVERSE_SPEED_KMS,
):
    """Estimate lens mass from tE under an explicit thin-lens geometry."""
    if (
        timescale_days is None
        or timescale_days <= 0.0
        or source_distance_pc is None
        or source_distance_pc <= 0.0
        or not 0.0 < lens_distance_fraction < 1.0
        or transverse_speed_kms <= 0.0
    ):
        return None

    source_distance_m = source_distance_pc * PARSEC_M
    lens_distance_m = source_distance_m * lens_distance_fraction
    lens_source_distance_m = source_distance_m - lens_distance_m
    transverse_speed_m_s = transverse_speed_kms * 1000.0
    einstein_crossing_s = timescale_days * 86_400.0
    einstein_radius_m = transverse_speed_m_s * einstein_crossing_s
    geometry = source_distance_m / (
        lens_distance_m * lens_source_distance_m
    )
    mass_kg = (
        SPEED_OF_LIGHT_M_S**2
        * einstein_radius_m**2
        * geometry
        / (4.0 * GRAVITATIONAL_CONSTANT)
    )
    mass_solar = mass_kg / SOLAR_MASS_KG
    return mass_solar if math.isfinite(mass_solar) and mass_solar > 0.0 else None


def _mass_scenario_range(timescale_days, source_distance_pc):
    """Return a sensitivity envelope, not a statistical confidence interval."""
    low_speed, high_speed = MASS_SCENARIO_SPEED_RANGE_KMS
    low_fraction, high_fraction = MASS_SCENARIO_DISTANCE_FRACTION_RANGE
    values = [
        _estimate_lens_mass(
            timescale_days,
            source_distance_pc,
            lens_distance_fraction=fraction,
            transverse_speed_kms=speed,
        )
        for speed in (low_speed, high_speed)
        for fraction in (
            low_fraction,
            ASSUMED_LENS_DISTANCE_FRACTION,
            high_fraction,
        )
    ]
    values = [value for value in values if value is not None]
    return (min(values), max(values)) if values else (None, None)


def _lens_mass_regime(lens_mass):
    if lens_mass is None or lens_mass <= 0.0:
        return {
            "label": None,
            "key": None,
            "note": "Brak masy pozwalającej porównać scenariusz z zakresami referencyjnymi.",
            "categories": [
                {"key": key, "label": label, "low": low, "high": high, "inRange": False}
                for key, label, low, high in LENS_MASS_RANGES
            ],
        }

    categories = [
        {
            "key": key,
            "label": label,
            "low": low,
            "high": high,
            "inRange": low <= lens_mass <= high,
        }
        for key, label, low, high in LENS_MASS_RANGES
    ]
    match = next((category for category in categories if category["inRange"]), None)
    if match:
        note = (
            f"Wartość {lens_mass:.3g} M☉ mieści się w przyjętym zakresie "
            f"referencyjnym „{match['label']}”. To zgodność zakresu masy, "
            "a nie identyfikacja obiektu."
        )
    else:
        note = (
            f"Wartość {lens_mass:.3g} M☉ nie mieści się w żadnym z trzech "
            "wyróżnionych zakresów referencyjnych."
        )

    return {
        "label": match["label"] if match else None,
        "key": match["key"] if match else None,
        "note": note,
        "categories": categories,
    }


def load_event_payload(catalog_path):
    console.print(f"  → Reading event catalogue: {catalog_path}")
    table = Table.read(catalog_path)
    required = {"source_id", "l", "b", "paczynski0_tmax", "paczynski0_te", "paczynski0_u0"}
    missing = sorted(required - set(table.colnames))
    if missing:
        raise KeyError(f"Missing FITS columns: {', '.join(missing)}")

    events = []
    rejected = Counter()
    seen_source_ids = set()
    for row in table:
        longitude = _finite(row["l"])
        latitude = _finite(row["b"])
        tmax = _finite(row["paczynski0_tmax"])
        timescale = _finite(row["paczynski0_te"])
        impact = _finite(row["paczynski0_u0"])
        if (
            longitude is None
            or latitude is None
            or tmax is None
            or timescale is None
            or impact is None
        ):
            rejected["brak wymaganych parametrów"] += 1
            continue
        if not 0.0 <= longitude <= 360.0 or not -90.0 <= latitude <= 90.0:
            rejected["współrzędne poza zakresem"] += 1
            continue
        if timescale <= 0.0:
            rejected["niedodatni czas tE"] += 1
            continue

        try:
            source_id = str(int(row["source_id"]))
        except (TypeError, ValueError, OverflowError):
            rejected["nieprawidłowe source_id"] += 1
            continue
        if source_id in seen_source_ids:
            rejected["duplikat source_id"] += 1
            continue
        seen_source_ids.add(source_id)
        impact = abs(impact)

        x, y = _hammer_position(longitude, latitude)
        date = _gaia_date(tmax)
        parallax = _finite(row["parallax"]) if "parallax" in table.colnames else None
        parallax_error = (
            _finite(row["parallax_error"])
            if "parallax_error" in table.colnames
            else None
        )
        if parallax is not None and parallax <= 0.0:
            parallax = None
        if parallax_error is not None and parallax_error <= 0.0:
            parallax_error = None
        distance_pc = 1000.0 / parallax if parallax is not None and parallax > 0.0 else None
        parallax_relative_error = (
            parallax_error / parallax
            if parallax is not None and parallax_error is not None
            else None
        )
        distance_low_pc = (
            1000.0 / (parallax + parallax_error)
            if parallax is not None and parallax_error is not None
            else None
        )
        distance_high_pc = (
            1000.0 / (parallax - parallax_error)
            if (
                parallax is not None
                and parallax_error is not None
                and parallax > parallax_error
            )
            else None
        )
        temperature, temperature_origin = _temperature_from_row(row)
        source_colour = _source_colour_from_row(row)
        catalog_lens_mass, mass_column = _first_finite(
            row,
            ("paczynski0_mass", "paczynski_mass", "lens_mass", "mass"),
        )
        if catalog_lens_mass is not None and catalog_lens_mass <= 0.0:
            catalog_lens_mass = None
            mass_column = None
        model_lens_mass = (
            _estimate_lens_mass(timescale, distance_pc)
            if catalog_lens_mass is None
            else None
        )
        lens_mass = catalog_lens_mass if catalog_lens_mass is not None else model_lens_mass
        mass_status = (
            "catalog"
            if catalog_lens_mass is not None
            else "model"
            if model_lens_mass is not None
            else "missing"
        )
        model_mass_low, model_mass_high = (
            _mass_scenario_range(timescale, distance_pc)
            if model_lens_mass is not None
            else (None, None)
        )
        lens_kind = None
        lens_kind_column = None
        for name in ("lens_type", "lens_class", "lens_object"):
            if name in table.colnames and not np.ma.is_masked(row[name]):
                text = str(row[name]).strip()
                if text:
                    lens_kind = text
                    lens_kind_column = name
                    break
        lens_regime = _lens_mass_regime(lens_mass)
        g_mag = _finite(row["phot_g_mean_mag"]) if "phot_g_mean_mag" in table.colnames else None
        if g_mag is not None and not -5.0 <= g_mag <= 40.0:
            g_mag = None
        bp_rp = _finite(row["bp_rp"]) if "bp_rp" in table.colnames else None
        if bp_rp is not None and not -5.0 <= bp_rp <= 15.0:
            bp_rp = None

        events.append(
            {
                "key": source_id,
                "sourceId": source_id,
                "l": longitude,
                "b": latitude,
                "x": x,
                "y": y,
                "tmax": tmax,
                "date": date,
                "te": timescale,
                "u0": impact,
                "aMax": _maximum_amplification(impact),
                "gMag": g_mag,
                "bpRp": bp_rp,
                "temperature": temperature,
                "temperatureOrigin": temperature_origin,
                "sourceColor": source_colour,
                "sourceDescription": _spectral_description(temperature),
                "parallax": parallax,
                "parallaxError": parallax_error,
                "parallaxRelativeError": parallax_relative_error,
                "distancePc": distance_pc,
                "distanceLowPc": distance_low_pc,
                "distanceHighPc": distance_high_pc,
                "distanceMethod": "odwrotność paralaksy bez korekty punktu zerowego",
                "catalogLensMass": catalog_lens_mass,
                "modelLensMass": model_lens_mass,
                "lensMass": lens_mass,
                "massOrigin": mass_column,
                "massStatus": mass_status,
                "massIsEstimated": mass_status == "model",
                "modelMassLow": model_mass_low,
                "modelMassHigh": model_mass_high,
                "modelDefaults": {
                    "transverseSpeedKms": ASSUMED_TRANSVERSE_SPEED_KMS,
                    "lensDistanceFraction": ASSUMED_LENS_DISTANCE_FRACTION,
                },
                "massEstimateNote": (
                    "Hipoteza modelowa, nie pomiar: wynik zależy od nieznanej "
                    "odległości soczewki i względnej prędkości poprzecznej."
                    if mass_status == "model"
                    else None
                ),
                "lensKind": lens_kind,
                "lensKindOrigin": lens_kind_column,
                "lensHypothesis": lens_regime["label"],
                "lensCategory": lens_regime["key"],
                "lensInferenceNote": lens_regime["note"],
                "lensCategories": lens_regime["categories"],
            }
        )

    events.sort(key=lambda event: event["tmax"])
    for index, event in enumerate(events, start=1):
        event["catalogIndex"] = index
        event["name"] = f"AUR–ML–{index:03d}"

    if not events:
        raise RuntimeError("No valid microlensing events remain after filtering")

    durations = np.asarray([event["te"] for event in events], dtype=float)
    amplifications = np.asarray([event["aMax"] for event in events], dtype=float)
    payload = {
        "meta": {
            "count": len(events),
            "dateStart": events[0]["date"]["date"],
            "dateEnd": events[-1]["date"]["date"],
            "medianTimescale": float(np.median(durations)),
            "strongCount": int(np.count_nonzero(amplifications >= 2.0)),
            "massKnownCount": sum(event["massStatus"] == "catalog" for event in events),
            "massModelCount": sum(event["massStatus"] == "model" for event in events),
            "inputCount": len(table),
            "filteredOutCount": sum(rejected.values()),
            "rejectionReasons": dict(rejected),
            "parallaxErrorCount": sum(event["parallaxError"] is not None for event in events),
            "projection": "Hammer, współrzędne galaktyczne",
            "catalog": catalog_path.name,
            "timeReference": "BJD(TCB) − 2455197.5",
        },
        "events": events,
    }
    console.print(f"  ✓ Prepared {len(events):,} valid events")
    return payload


def find_sky_map(explicit_path=None):
    if explicit_path:
        path = Path(explicit_path).expanduser().resolve()
        if path.is_file():
            return path
        raise FileNotFoundError(f"Sky map does not exist: {path}")

    candidates = [map_path(SKY_MAP_NAME)]
    for candidate in candidates:
        if candidate.is_file():
            return candidate.resolve()
    checked = "\n".join(f"    - {path}" for path in candidates)
    raise FileNotFoundError(
        "The Hammer sky map has not been generated yet.\n"
        "Run main/aurora_sky_render.py first, or use --map PATH.\n"
        f"Checked:\n{checked}"
    )


