def draw_text_block(
    canvas: np.ndarray,
    lines: tuple[str, ...] | list[str],
    *,
    x: int | None = None,
    y: int | None = None,
    scale: int | None = None,
    dim_background: bool = True,
) -> None:
    """Draw compact labels without changing the renderer's image dependencies."""
    scale = max(1, int(round(canvas.shape[0] / 480.0))) if scale is None else max(1, int(scale))
    x = 8 * scale if x is None else x
    y = 8 * scale if y is None else y
    line_height = 9 * scale
    width = max((len(line) for line in lines), default=0) * 6 * scale + 8 * scale
    height = len(lines) * line_height + 7 * scale
    x1 = min(canvas.shape[1], x + width)
    y1 = min(canvas.shape[0], y + height)
    if dim_background:
        panel = canvas[y:y1, x:x1].astype(np.float32)
        canvas[y:y1, x:x1] = np.rint(panel * 0.42).astype(np.uint8)

    cursor_y = y + 3 * scale
    for line in lines:
        cursor_x = x + 4 * scale
        for character in line.upper():
            glyph = _FONT.get(character, _FONT["?"])
            for row, bits in enumerate(glyph):
                for column, bit in enumerate(bits):
                    if bit == "1":
                        yy = cursor_y + row * scale
                        xx = cursor_x + column * scale
                        canvas[yy : yy + scale, xx : xx + scale] = (235, 240, 245)
            cursor_x += 6 * scale
            if cursor_x >= canvas.shape[1] - 6 * scale:
                break
        cursor_y += line_height
        if cursor_y >= canvas.shape[0] - 7 * scale:
            break
